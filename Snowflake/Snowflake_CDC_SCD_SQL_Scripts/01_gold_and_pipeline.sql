CREATE OR REPLACE PROCEDURE GOLD_DB.SALES_MART.SP_BUILD_DAILY_SUMMARY()
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    v_start TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP();
BEGIN
    DELETE FROM GOLD_DB.SALES_MART.DAILY_SALES_SUMMARY
    WHERE ORDER_DATE_KEY >= TRY_TO_NUMBER(TO_CHAR(DATEADD('day',-3,CURRENT_DATE()),'YYYYMMDD'));

    INSERT INTO GOLD_DB.SALES_MART.DAILY_SALES_SUMMARY (
        ORDER_DATE_KEY, FULL_DATE, REGION_ID, SEGMENT,
        ORDER_COUNT, UNIQUE_CUSTOMERS, GROSS_REVENUE, NET_REVENUE,
        TOTAL_PROFIT, AVG_ORDER_VALUE, PROFIT_MARGIN_PCT
    )
    SELECT
        f.ORDER_DATE_KEY,
        d.FULL_DATE,
        s.REGION_ID,
        c.SEGMENT,             -- SCD2 segment at time of order
        COUNT(DISTINCT f.ORDER_ID)         AS ORDER_COUNT,
        COUNT(DISTINCT f.SK_CUSTOMER)      AS UNIQUE_CUSTOMERS,
        SUM(f.TOTAL_AMOUNT)                AS GROSS_REVENUE,
        SUM(f.NET_AMOUNT)                  AS NET_REVENUE,
        SUM(f.PROFIT)                      AS TOTAL_PROFIT,
        AVG(f.TOTAL_AMOUNT)                AS AVG_ORDER_VALUE,
        CASE WHEN SUM(f.NET_AMOUNT)>0
             THEN (SUM(f.PROFIT)/SUM(f.NET_AMOUNT))*100 ELSE 0 END AS PROFIT_MARGIN_PCT
    FROM SILVER_DB.FACTS.FACT_ORDERS f
    JOIN SILVER_DB.DIMENSIONS.DIM_DATE d ON d.DATE_KEY = f.ORDER_DATE_KEY
    LEFT JOIN SILVER_DB.DIMENSIONS.DIM_CUSTOMERS c ON c.SK_CUSTOMER = f.SK_CUSTOMER
    LEFT JOIN SILVER_DB.DIMENSIONS.DIM_STORES s ON s.SK_STORE = f.SK_STORE
    WHERE f.ORDER_DATE_KEY >= TRY_TO_NUMBER(TO_CHAR(DATEADD('day',-3,CURRENT_DATE()),'YYYYMMDD'))
    GROUP BY 1,2,3,4;

    RETURN OBJECT_CONSTRUCT('status','SUCCESS',
        'duration_sec',DATEDIFF('second',:v_start,CURRENT_TIMESTAMP()));
EXCEPTION WHEN OTHER THEN RETURN OBJECT_CONSTRUCT('status','FAILED','error',SQLERRM);
END;
$$;

CREATE OR REPLACE PROCEDURE GOLD_DB.CUSTOMER_MART.SP_BUILD_CUSTOMER_360()
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE v_start TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP();
BEGIN
    TRUNCATE TABLE GOLD_DB.CUSTOMER_MART.CUSTOMER_360;

    INSERT INTO GOLD_DB.CUSTOMER_MART.CUSTOMER_360
    WITH METRICS AS (
        SELECT SK_CUSTOMER,
            COUNT(DISTINCT ORDER_ID)        AS TOTAL_ORDERS,
            SUM(TOTAL_AMOUNT)               AS TOTAL_REVENUE,
            AVG(TOTAL_AMOUNT)               AS AVG_ORDER_VALUE,
            DATEDIFF('day',MAX(TO_DATE(ORDER_DATE_KEY::VARCHAR,'YYYYMMDD')),CURRENT_DATE()) AS DAYS_SINCE_LAST
        FROM SILVER_DB.FACTS.FACT_ORDERS GROUP BY 1
    ),
    RFM AS (
        SELECT *,
            NTILE(5) OVER (ORDER BY DAYS_SINCE_LAST ASC) +
            NTILE(5) OVER (ORDER BY TOTAL_ORDERS DESC) +
            NTILE(5) OVER (ORDER BY TOTAL_REVENUE DESC) AS RFM_SCORE
        FROM METRICS
    ),
    SCD_COUNTS AS (
        -- Count how many times segment/loyalty changed per customer
        SELECT CUSTOMER_ID,
            COUNT(*) - 1                                                              AS SEGMENT_CHANGES,
            COUNT(DISTINCT LOYALTY_TIER) - 1                                          AS LOYALTY_CHANGES
        FROM SILVER_DB.DIMENSIONS.DIM_CUSTOMERS
        GROUP BY 1
    )
    SELECT
        c.SK_CUSTOMER, c.CUSTOMER_ID, c.CUSTOMER_NAME, c.EMAIL,
        c.SEGMENT, c.LOYALTY_TIER, c.REGION_ID,
        m.TOTAL_ORDERS, m.TOTAL_REVENUE, m.AVG_ORDER_VALUE, m.DAYS_SINCE_LAST,
        sc.SEGMENT_CHANGES, sc.LOYALTY_CHANGES,
        r.RFM_SCORE,
        CASE WHEN r.RFM_SCORE >= 12 THEN 'Platinum'
             WHEN r.RFM_SCORE >= 9  THEN 'Gold'
             WHEN r.RFM_SCORE >= 6  THEN 'Silver'
             ELSE 'Bronze' END AS CUSTOMER_TIER
    FROM RFM r
    JOIN SILVER_DB.DIMENSIONS.DIM_CUSTOMERS c ON c.SK_CUSTOMER=r.SK_CUSTOMER AND c.IS_CURRENT=TRUE
    LEFT JOIN SCD_COUNTS sc ON sc.CUSTOMER_ID=c.CUSTOMER_ID;

    RETURN OBJECT_CONSTRUCT('status','SUCCESS',
        'duration_sec',DATEDIFF('second',:v_start,CURRENT_TIMESTAMP()));
EXCEPTION WHEN OTHER THEN RETURN OBJECT_CONSTRUCT('status','FAILED','error',SQLERRM);
END;
$$;

