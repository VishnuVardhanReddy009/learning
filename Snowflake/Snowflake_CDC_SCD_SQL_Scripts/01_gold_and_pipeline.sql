USE SCHEMA REPORTING;

CREATE MATERIALIZED VIEW IF NOT EXISTS MV_DAILY_KPI AS
SELECT
    d.FULL_DATE, d.YEAR, d.MONTH_NAME, d.QUARTER_NAME,
    f.STATUS,
    c.SEGMENT, c.LOYALTY_TIER,
    COUNT(DISTINCT f.ORDER_ID)        ORDERS,
    COUNT(DISTINCT f.SK_CUSTOMER)     CUSTOMERS,
    SUM(f.TOTAL_AMOUNT)               GROSS_REVENUE,
    SUM(f.NET_AMOUNT)                 NET_REVENUE,
    SUM(f.PROFIT)                     PROFIT,
    AVG(f.TOTAL_AMOUNT)               AVG_ORDER_VALUE
FROM SILVER_DB.FACTS.FACT_ORDERS f
JOIN SILVER_DB.DIMENSIONS.DIM_DATE d ON d.DATE_KEY=f.ORDER_DATE_KEY
LEFT JOIN SILVER_DB.DIMENSIONS.DIM_CUSTOMERS c ON c.SK_CUSTOMER=f.SK_CUSTOMER
GROUP BY 1,2,3,4,5,6,7;

CREATE SECURE VIEW IF NOT EXISTS V_SEGMENT_PERFORMANCE AS
SELECT
    d.YEAR, d.QUARTER_NAME, d.MONTH_NAME,
    c.SEGMENT,
    c.LOYALTY_TIER,
    COUNT(DISTINCT f.ORDER_ID)   AS ORDERS,
    SUM(f.NET_AMOUNT)            AS NET_REVENUE,
    AVG(f.NET_AMOUNT)            AS AVG_ORDER_VALUE,
    SUM(f.PROFIT)                AS PROFIT,
    -- Window: running total by segment per year
    SUM(SUM(f.NET_AMOUNT)) OVER (
        PARTITION BY d.YEAR, c.SEGMENT
        ORDER BY d.MONTH_NUM
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS YTD_REVENUE_BY_SEGMENT
FROM SILVER_DB.FACTS.FACT_ORDERS f
JOIN SILVER_DB.DIMENSIONS.DIM_DATE d ON d.DATE_KEY=f.ORDER_DATE_KEY
LEFT JOIN SILVER_DB.DIMENSIONS.DIM_CUSTOMERS c ON c.SK_CUSTOMER=f.SK_CUSTOMER
GROUP BY 1,2,3,4,5;

-- SCD2 Analysis View — show customer journey across segment changes
CREATE SECURE VIEW IF NOT EXISTS V_CUSTOMER_SEGMENT_JOURNEY AS
SELECT
    h.CUSTOMER_ID,
    h.VERSION_NUM,
    h.SEGMENT                   AS SEGMENT_AT_VERSION,
    h.LOYALTY_TIER              AS LOYALTY_AT_VERSION,
    h.PREV_SEGMENT              AS PREV_SEGMENT,     -- Type 3 column
    h.PREV_LOYALTY_TIER         AS PREV_LOYALTY,
    h.EFF_START_DATE,
    h.EFF_END_DATE,
    COALESCE(h.EFF_END_DATE, CURRENT_DATE()) - h.EFF_START_DATE AS DAYS_AT_VERSION,
    h.CDC_OPERATION,
    h.CHANGED_COLS,
    SUM(COALESCE(f.TOTAL_AMOUNT,0)) OVER (
        PARTITION BY h.CUSTOMER_ID, h.SK_CUSTOMER
    ) AS REVENUE_IN_THIS_VERSION  -- how much did customer spend while at this segment
FROM SILVER_DB.DIMENSIONS.DIM_CUSTOMERS h
LEFT JOIN SILVER_DB.FACTS.FACT_ORDERS f
    ON f.SK_CUSTOMER = h.SK_CUSTOMER   -- FK is to the version active at order time
ORDER BY h.CUSTOMER_ID, h.VERSION_NUM;

