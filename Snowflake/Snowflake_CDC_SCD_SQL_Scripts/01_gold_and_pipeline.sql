USE ROLE DATA_ENG_ROLE;
USE DATABASE COMMON_DB;
USE SCHEMA UTILITIES;

-- Audit log for pipeline
CREATE TABLE IF NOT EXISTS COMMON_DB.AUDIT.PIPELINE_LOG (
    LOG_ID      NUMBER AUTOINCREMENT PRIMARY KEY,
    BATCH_ID    VARCHAR(100),
    TASK_NAME   VARCHAR(100),
    STATUS      VARCHAR(20),
    STARTED_AT  TIMESTAMP_NTZ,
    ENDED_AT    TIMESTAMP_NTZ,
    ROWS_PROC   NUMBER,
    RESULT      VARIANT,
    CREATED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- ── ROOT TASK ────────────────────────────────────────────────
CREATE OR REPLACE TASK TASK_CDC_PIPELINE_ROOT
    WAREHOUSE         = TRANSFORM_WH
    SCHEDULE          = 'USING CRON 0 * * * * UTC'   -- every hour
    ERROR_INTEGRATION = SNS_ALERTS
    USER_TASK_TIMEOUT_MS = 3600000
    COMMENT = 'Root: hourly CDC pipeline — only runs when Bronze streams have data'
    WHEN
        SYSTEM$STREAM_HAS_DATA('CDC_DB.STREAMS.STR_CUSTOMERS') OR
        SYSTEM$STREAM_HAS_DATA('CDC_DB.STREAMS.STR_PRODUCTS')  OR
        SYSTEM$STREAM_HAS_DATA('CDC_DB.STREAMS.STR_ORDERS')    OR
        SYSTEM$STREAM_HAS_DATA('CDC_DB.STREAMS.STR_EMPLOYEES') OR
        SYSTEM$STREAM_HAS_DATA('CDC_DB.STREAMS.STR_STORES')
AS
DECLARE
    batch_id VARCHAR;
BEGIN
    batch_id := 'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS');
    INSERT INTO COMMON_DB.AUDIT.PIPELINE_LOG (BATCH_ID,TASK_NAME,STATUS,STARTED_AT)
    VALUES (:batch_id,'ROOT','RUNNING',CURRENT_TIMESTAMP());
END;

-- ── CDC CLASSIFY TASKS (parallel) ────────────────────────────
CREATE OR REPLACE TASK TASK_CLASSIFY_CUSTOMERS
    WAREHOUSE=TRANSFORM_WH AFTER TASK_CDC_PIPELINE_ROOT
    ERROR_INTEGRATION=SNS_ALERTS
AS
    CALL CDC_DB.CONTROL.SP_CLASSIFY_CUSTOMER_CHANGES(
        'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS')
    );

CREATE OR REPLACE TASK TASK_CLASSIFY_PRODUCTS
    WAREHOUSE=TRANSFORM_WH AFTER TASK_CDC_PIPELINE_ROOT
    ERROR_INTEGRATION=SNS_ALERTS
AS
    CALL CDC_DB.CONTROL.SP_CLASSIFY_CUSTOMER_CHANGES(
        'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS')
    );

CREATE OR REPLACE TASK TASK_CLASSIFY_EMPLOYEES
    WAREHOUSE=TRANSFORM_WH AFTER TASK_CDC_PIPELINE_ROOT
    ERROR_INTEGRATION=SNS_ALERTS
AS
    CALL CDC_DB.CONTROL.SP_CLASSIFY_CUSTOMER_CHANGES(
        'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS')
    );

-- ── SCD2 DIMENSION TASKS (after classify) ────────────────────
CREATE OR REPLACE TASK TASK_SCD2_CUSTOMERS
    WAREHOUSE=TRANSFORM_WH
    AFTER TASK_CLASSIFY_CUSTOMERS, TASK_CLASSIFY_EMPLOYEES
    ERROR_INTEGRATION=SNS_ALERTS
AS
    CALL SILVER_DB.DIMENSIONS.SP_SCD2_CUSTOMERS(
        'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS')
    );

CREATE OR REPLACE TASK TASK_SCD2_PRODUCTS
    WAREHOUSE=TRANSFORM_WH
    AFTER TASK_CLASSIFY_PRODUCTS
    ERROR_INTEGRATION=SNS_ALERTS
AS
    CALL SILVER_DB.DIMENSIONS.SP_SCD2_PRODUCTS(
        'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS')
    );

CREATE OR REPLACE TASK TASK_SCD1_STORES
    WAREHOUSE=TRANSFORM_WH AFTER TASK_CDC_PIPELINE_ROOT
    ERROR_INTEGRATION=SNS_ALERTS
AS
    CALL SILVER_DB.DIMENSIONS.SP_SCD1_STORES(
        'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS')
    );

-- ── FACT LOAD (after ALL dims) ────────────────────────────────
CREATE OR REPLACE TASK TASK_LOAD_FACTS
    WAREHOUSE=TRANSFORM_WH
    AFTER TASK_SCD2_CUSTOMERS, TASK_SCD2_PRODUCTS, TASK_SCD1_STORES
    ERROR_INTEGRATION=SNS_ALERTS
AS
    CALL SILVER_DB.FACTS.SP_LOAD_FACT_ORDERS(
        'BATCH_' || TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS')
    );

-- ── GOLD BUILD (after facts) ──────────────────────────────────
CREATE OR REPLACE TASK TASK_BUILD_DAILY_SUMMARY
    WAREHOUSE=TRANSFORM_WH AFTER TASK_LOAD_FACTS
    ERROR_INTEGRATION=SNS_ALERTS
AS  CALL GOLD_DB.SALES_MART.SP_BUILD_DAILY_SUMMARY();

CREATE OR REPLACE TASK TASK_BUILD_CUSTOMER_360
    WAREHOUSE=TRANSFORM_WH AFTER TASK_LOAD_FACTS
    ERROR_INTEGRATION=SNS_ALERTS
AS  CALL GOLD_DB.CUSTOMER_MART.SP_BUILD_CUSTOMER_360();

-- ── SUCCESS NOTIFICATION ──────────────────────────────────────
CREATE OR REPLACE TASK TASK_PIPELINE_COMPLETE
    WAREHOUSE=TRANSFORM_WH
    AFTER TASK_BUILD_DAILY_SUMMARY, TASK_BUILD_CUSTOMER_360
AS
    INSERT INTO COMMON_DB.AUDIT.PIPELINE_LOG
        (BATCH_ID,TASK_NAME,STATUS,STARTED_AT,ENDED_AT)
    VALUES (
        'BATCH_'||TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDD_HH24MISS'),
        'PIPELINE_COMPLETE','SUCCESS',CURRENT_TIMESTAMP(),CURRENT_TIMESTAMP()
    );

-- ── RESUME ORDER: LEAVES FIRST, ROOT LAST ────────────────────
ALTER TASK TASK_PIPELINE_COMPLETE     RESUME;
ALTER TASK TASK_BUILD_CUSTOMER_360    RESUME;
ALTER TASK TASK_BUILD_DAILY_SUMMARY   RESUME;
ALTER TASK TASK_LOAD_FACTS            RESUME;
ALTER TASK TASK_SCD1_STORES           RESUME;
ALTER TASK TASK_SCD2_PRODUCTS         RESUME;
ALTER TASK TASK_SCD2_CUSTOMERS        RESUME;
ALTER TASK TASK_CLASSIFY_EMPLOYEES    RESUME;
ALTER TASK TASK_CLASSIFY_PRODUCTS     RESUME;
ALTER TASK TASK_CLASSIFY_CUSTOMERS    RESUME;
ALTER TASK TASK_CDC_PIPELINE_ROOT     RESUME;   -- LAST

-- ── PIPELINE MONITORING QUERIES ───────────────────────────────
SELECT NAME, STATE, ERROR_MESSAGE, SCHEDULED_TIME, COMPLETED_TIME,
    DATEDIFF('second',QUERY_START_TIME,COMPLETED_TIME) AS SEC
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
    SCHEDULED_TIME_RANGE_START => DATEADD('hour',-24,CURRENT_TIMESTAMP())
))
ORDER BY SCHEDULED_TIME DESC;
